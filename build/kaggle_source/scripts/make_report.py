"""Generate results/summary.md and refresh the generated block inside README.md.

    python scripts/make_report.py --out results --readme README.md

The generated block is delimited by HTML comments; everything outside it is hand-written and preserved.
`tests/test_report.py` re-renders the block from results/*.json and fails if README drifted - that is
the mechanism behind "no number in this repo was typed by hand".
"""
from __future__ import annotations

import argparse
from pathlib import Path

from codedet.report import render_results_block, splice_generated
from codedet.utils import get_logger, read_json

log = get_logger("make_report")


def load(path: Path) -> dict:
    return read_json(path) if path.exists() else {}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results")
    ap.add_argument("--readme", default="README.md")
    a = ap.parse_args()

    out = Path(a.out)
    summary, analysis, bench = load(out / "summary.json"), load(out / "analysis.json"), load(out / "bench.json")
    if not summary:
        log.warning("no summary.json; run evaluate.py first")
        return 1
    block = render_results_block(summary, analysis, bench)

    figures = sorted(p.name for p in (out / "figures").glob("*.png"))
    md = ["# Results", "",
          f"Generated by `scripts/make_report.py` from the JSON in `{a.out}/`. Do not edit by hand.", "",
          block, ""]
    if figures:
        md += ["## Figures", ""] + [f"![{f}](figures/{f})" for f in figures] + [""]
    status = load(out / "status.json")
    if status:
        md += ["## Run status", "",
               "| stage | status | seconds | note |", "|---|---|---|---|"]
        for s in status.get("stages", []):
            md.append(f"| {s['stage']} | {s['status']} | {s.get('seconds', 0):.0f} | "
                      f"{(s.get('error') or s.get('degradation') or '')[:80]} |")
        md.append("")
    (out / "summary.md").write_text("\n".join(md), encoding="utf-8")
    log.info(f"wrote {out / 'summary.md'}")

    readme = Path(a.readme)
    if readme.exists():
        readme.write_text(splice_generated(readme.read_text(encoding="utf-8"), block), encoding="utf-8")
        log.info(f"refreshed generated block in {readme}")
    print(f"wrote {out / 'summary.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
